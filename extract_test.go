// TestRedaction is the fixture required by PLAN.md 1d: a string containing each
// pattern comes out fully redacted with surrounding prose intact.
func TestRedaction(t *testing.T) {
	// One representative hit per pattern, embedded in prose. Each non-secret
	// word must survive; every secret must collapse to exactly [REDACTED].
	const input = `Before anything, the key was sk-live12345678901234567890.
Then we set GH_TOKEN=ghp_0123456789abcdef0123456789abcdef0123.
The fine-grained PAT github_pat_11ABCD2EFGHIJKLMNOPQRSTUVWXYZ_qwerty was also leaked.
AWS had AKIAIOSFODNN7EXAMPLE attached to the box.
Slack token xoxb-1234567890-abcdef sits in env.
The DB url is postgres://user:sup3rs3cret@db.example.com:5432/app?sslmode=disable
or mysql://app:hunter2@10.0.0.5:3306/svc for the legacy shard.
Auth header was Authorization: Bearer eyJhbGciOiJIUzI1NiJ9.payload.sig
and the signing key was:
-----BEGIN RSA PRIVATE KEY-----
MIIEpAIBAAKCAQEAabcd1234FAKEKEYf0rTestingPurposesOnlyDoNotUseReal
-----END RSA PRIVATE KEY-----
After all that, we shipped the auth feature.`

	got := redact(input)

	// Surrounding prose must survive (a sampling of sentences).
	for _, want := range []string{
		"Before anything, the key was",
		"Then we set GH_TOKEN=",
		"AWS had",
		"Slack token",
		"The DB url is",
		"Auth header was",
		"After all that, we shipped the auth feature.",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("prose dropped by redaction: missing %q\n got: %s", want, got)
		}
	}

	// No secret material may survive. Each of these fragments appears in the
	// input but must NOT appear in the output.
	for _, leaked := range []string{
		"sk-live12345678901234567890",
		"ghp_0123456789abcdef0123456789abcdef0123",
		"github_pat_11ABCD2EFGHIJKLMNOPQRSTUVWXYZ_qwerty",
		"AKIAIOSFODNN7EXAMPLE",
		"xoxb-1234567890-abcdef",
		"sup3rs3cret",
		"hunter2",
		"eyJhbGciOiJIUzI1NiJ9.payload.sig",
		"MIIEpAIBAAKCAQEAabcd1234FAKEKEYf0rTestingPurposesOnlyDoNotUseReal",
		"MIIEpAIBAA",
	} {
		if strings.Contains(got, leaked) {
			t.Errorf("secret survived redaction: %q\n got: %s", leaked, got)
		}
	}

	// Every secret must have been replaced with the literal token. Count must
	// match the number of patterns fired (9: one each per pattern, with two DB
	// URLs counted separately — postgres + mysql). We check by ensuring each
	// replacement site is present.
	wantRedactions := 9
	if c := strings.Count(got, "[REDACTED]"); c != wantRedactions {
		t.Errorf("expected %d [REDACTED] tokens, got %d\n got: %s", wantRedactions, c, got)
	}
}

func TestRedactionKeepsNonSecretsUntouched(t *testing.T) {
	in := "plain text with no secrets, just sk-mentioned as a substring"
	out := redact(in)
	if out != in {
		t.Errorf("non-secret text modified:\n in:  %q\n out: %q", in, out)
	}
}

