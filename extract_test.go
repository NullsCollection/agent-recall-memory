// --- extraction end-to-end on a synthetic session ---

func TestExtractFileEndToEnd(t *testing.T) {
	// Two turns:
	//  1. normal: user asks → assistant answers + tool
	//  2. short approval: should borrow turn 1's assistant text
	const session = `{"type":"user","uuid":"u1","cwd":"/home/u/myrepo","timestamp":"2025-01-02T15:04:05Z","message":{"role":"user","content":"how do I configure the database connection?"}}
{"type":"assistant","uuid":"a1","timestamp":"2025-01-02T15:04:06Z","message":{"role":"assistant","content":[{"type":"text","text":"Use the DATABASE_URL env var."},{"type":"tool_use","name":"Read","input":{}}]}}
{"type":"user","uuid":"u2","cwd":"/home/u/myrepo","timestamp":"2025-01-02T15:05:00Z","message":{"role":"user","content":"ok"}}
{"type":"assistant","uuid":"a2","timestamp":"2025-01-02T15:05:01Z","message":{"role":"assistant","content":[{"type":"text","text":"Great, marking done."}]}}
`
	tmp := t.TempDir() + "/s.jsonl"
	mustWrite(t, tmp, session)

	units, err := extractFile(tmp, "sessionA", shortTurnChars)
	if err != nil {
		t.Fatal(err)
	}
	if len(units) != 2 {
		t.Fatalf("expected 2 units, got %d: %+v", len(units), units)
	}

	// Unit 0: normal fused turn.
	u0 := units[0]
	if !strings.HasPrefix(u0.Text, "User: how do I configure") {
		t.Errorf("u0 text: %q", u0.Text)
	}
	if !strings.Contains(u0.Text, "Assistant: Use the DATABASE_URL") {
		t.Errorf("u0 missing assistant: %q", u0.Text)
	}
	if !strings.Contains(u0.Text, "Tools: Read") {
		t.Errorf("u0 missing tools: %q", u0.Text)
	}
	if u0.Repo != "myrepo" {
		t.Errorf("u0 repo=%q want myrepo", u0.Repo)
	}
	if u0.TS != 1735830245 {
		t.Errorf("u0 ts=%d want 1735830245 (2025-01-02T15:04:05Z)", u0.TS)
	}

	// Unit 1: short turn that borrowed the previous assistant message.
	u1 := units[1]
	if !strings.HasPrefix(u1.Text, "Assistant: Use the DATABASE_URL") {
		t.Errorf("u1 should start with borrowed assistant: %q", u1.Text)
	}
	if !strings.Contains(u1.Text, "User: ok") {
		t.Errorf("u1 should still contain the approval: %q", u1.Text)
	}

	// ids must be deterministic.
	id0 := sha256Hex("sessionA:u1")
	if units[0].ID != id0 {
		t.Errorf("u0 id=%q want %q", units[0].ID, id0)
	}
}

